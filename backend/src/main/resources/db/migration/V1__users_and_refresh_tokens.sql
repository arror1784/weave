-- 사용자와 리프레시 토큰 (인증)

CREATE TABLE IF NOT EXISTS users (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at             TIMESTAMPTZ NOT NULL,
    updated_at             TIMESTAMPTZ NOT NULL,
    deleted_at             TIMESTAMPTZ,
    -- 개인정보: 탈퇴 시 행째 삭제한다(§3-17)
    email                  VARCHAR(320) NOT NULL,
    password_hash          VARCHAR(100) NOT NULL,
    -- 하루 가용 시간(시간) — 일정 배정·과부하 기준, 기본 3시간(사용자 결정)
    daily_available_hours  DOUBLE PRECISION NOT NULL DEFAULT 3
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email ON users (email) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    deleted_at   TIMESTAMPTZ,
    user_id      BIGINT NOT NULL REFERENCES users (id),
    -- 토큰 원문은 저장하지 않고 SHA-256 해시만 (§3-3)
    token_hash   VARCHAR(64) NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    -- 교체(rotation)·로그아웃·재사용 감지로 폐기된 시각
    revoked_at   TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_refresh_tokens_token_hash ON refresh_tokens (token_hash);
CREATE INDEX IF NOT EXISTS ix_refresh_tokens_user_id ON refresh_tokens (user_id);

-- 사용 기록 (사용자 결정 2026-10-07): 프로젝트·작업·AI 챗봇(대화 본문 포함)·앱 사용·설정·첨부 활동을 남긴다.
-- 개인정보가 담긴다(AI 대화 본문·파일 이름·프로젝트 이름) — 탈퇴 시 행째 삭제한다(§3-17).
CREATE TABLE IF NOT EXISTS activity_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    deleted_at   TIMESTAMPTZ,
    user_id      BIGINT NOT NULL REFERENCES users (id),
    -- 활동이 일어난 시각 (앱 기록은 앱이 보낸 시각)
    occurred_at  TIMESTAMPTZ NOT NULL,
    -- 활동 종류 (예: PROJECT_CREATED, TASK_DONE, AI_CHAT, APP_OPENED)
    type         VARCHAR(40) NOT NULL,
    -- 관련 프로젝트·작업 (지워진 뒤에도 기록은 남아야 해서 FK를 걸지 않는다)
    project_id   BIGINT,
    task_id      BIGINT,
    -- 세부 내용 JSON
    detail       TEXT NOT NULL DEFAULT '{}',
    -- 'server' 서버가 남김 · 'app' 앱이 보냄 · 'backfill' 기능 전 데이터에서 채움
    source       VARCHAR(10) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_activity_logs_user_occurred ON activity_logs (user_id, occurred_at);

-- 작업 완료 시각 — 완료를 풀면 지운다
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS done_at TIMESTAMPTZ;

-- 프로젝트와 작업

CREATE TABLE IF NOT EXISTS projects (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMPTZ NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL,
    deleted_at   TIMESTAMPTZ,
    user_id      BIGINT NOT NULL REFERENCES users (id),
    -- 개인정보가 담길 수 있는 글 — 탈퇴 시 행째 삭제한다(§3-17)
    name         VARCHAR(100) NOT NULL,
    description  VARCHAR(2000) NOT NULL DEFAULT '',
    -- 프로젝트 마감일. NULL이면 상시
    deadline     DATE,
    -- 'active' | 'done'
    status       VARCHAR(10) NOT NULL DEFAULT 'active',
    -- 사용자가 고른 색 키 (teal·magenta·violet·gray·blue·green·amber·brown)
    color        VARCHAR(20) NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_projects_user_id ON projects (user_id);

CREATE TABLE IF NOT EXISTS tasks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL,
    deleted_at       TIMESTAMPTZ,
    project_id       BIGINT NOT NULL REFERENCES projects (id),
    -- AI가 제안한(검토 단계에서 고친) 순서
    position         INT NOT NULL,
    title            VARCHAR(200) NOT NULL,
    estimated_hours  DOUBLE PRECISION,
    -- 선행 작업(같은 프로젝트, 최대 1개)
    depends_on_id    BIGINT REFERENCES tasks (id),
    -- 일정 알고리즘이 배정한 시작일·기간·작업 마감일
    scheduled_date   DATE,
    span_days        INT NOT NULL DEFAULT 1,
    due_date         DATE,
    done             BOOLEAN NOT NULL DEFAULT FALSE,
    -- AI가 "선행 학습"으로 넣은 작업
    prerequisite     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS ix_tasks_project_id ON tasks (project_id);
CREATE INDEX IF NOT EXISTS ix_tasks_depends_on_id ON tasks (depends_on_id);

-- 프로젝트 참고자료 첨부 (링크·파일·사진). 등록 전에 먼저 올리고, 프로젝트를 등록할 때 연결한다.

CREATE TABLE IF NOT EXISTS attachments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    deleted_at    TIMESTAMPTZ,
    user_id       BIGINT NOT NULL REFERENCES users (id),
    -- 프로젝트 등록 전에는 NULL
    project_id    BIGINT REFERENCES projects (id),
    -- 'link' | 'file' | 'image'
    kind          VARCHAR(10) NOT NULL,
    -- 개인정보가 담길 수 있음 — 탈퇴 시 행과 파일을 실제로 삭제한다(§3-17)
    name          VARCHAR(300) NOT NULL,
    -- 링크 주소 (kind = link)
    url           VARCHAR(2000),
    -- 서버가 만든 저장 파일 이름 (kind = file·image, §3-9)
    storage_key   VARCHAR(100),
    content_type  VARCHAR(100),
    size_bytes    BIGINT
);

CREATE INDEX IF NOT EXISTS ix_attachments_user_id ON attachments (user_id);
CREATE INDEX IF NOT EXISTS ix_attachments_project_id ON attachments (project_id);

-- 개인 일정(사용자 결정 2026-10-17): 매주 반복(요일·기간) 또는 한 번(날짜). 그날 가용 시간에서 일정 시간만큼 뺀다.
-- 개인정보(일정 이름·시각) — 탈퇴 시 행째 삭제한다(§3-17, AccountDeletionService).
CREATE TABLE IF NOT EXISTS personal_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    deleted_at  TIMESTAMPTZ,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    title       VARCHAR(100) NOT NULL,
    -- 'weekly' 매주 반복 · 'once' 한 번
    repeat_type VARCHAR(10) NOT NULL,
    -- 반복 요일 — 월요일 1 … 일요일 7, 쉼표로 (예: '1,3')
    weekdays    VARCHAR(20) NOT NULL DEFAULT '',
    -- 한 번 일정의 날짜
    event_date  DATE,
    start_time  TIME NOT NULL,
    end_time    TIME NOT NULL,
    -- 반복 기간(비우면 처음부터·계속)
    start_date  DATE,
    end_date    DATE
);
CREATE INDEX IF NOT EXISTS ix_personal_events_user ON personal_events (user_id);

